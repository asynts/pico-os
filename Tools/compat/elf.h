#define ET_REL 1

#define EV_CURRENT 1

#define SHN_UNDEF 0

#define SHT_NULL     0
#define SHT_PROGBITS 1
#define SHT_SYMTAB   2
#define SHT_STRTAB   3
#define SHT_RELA     4
#define SHT_NOBITS   8
#define SHT_REL      9

#define SHF_WRITE 1
#define SHF_ALLOC 2

#define STB_GLOBAL 1

#define STT_OBJECT 1

#define STV_DEFAULT 0

